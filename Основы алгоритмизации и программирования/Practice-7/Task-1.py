rating = input("Введите рейтинг продуктов (от 1 до 10): ")

match rating:
    case "8" | "9" | "10":
        conclusion = "Отличный продукт! 🌟 Настоятельно рекомендую!"
    case  "4" | "5" | "6" | "7":
        conclusion = "Средний продукт 😐 Можно попробовать"
    case "1" | "2" | "3":
        conclusion = "Плохой продукт ❌ Не рекомендую"
    case _:
        conclusion = "❌ Ошибка: введите число от 1 до 10"

print(f"Рейтинг {rating}: {conclusion}")